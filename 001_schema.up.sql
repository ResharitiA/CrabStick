BEGIN;

CREATE TABLE public.accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    balance bigint NOT NULL DEFAULT 0 CHECK (balance >= 0),
    "withdrawBalance" bigint NOT NULL DEFAULT 0 CHECK ("withdrawBalance" >= 0),
    "totalReplenished" bigint NOT NULL DEFAULT 0 CHECK ("totalReplenished" >= 0),
    "bonusBalance" bigint NOT NULL DEFAULT 0 CHECK ("bonusBalance" >= 0),
    "bonusState" text NOT NULL DEFAULT 'locked'
        CHECK ("bonusState" IN ('locked', 'unlocked'))
);

CREATE TABLE public.services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (name ~ '^[A-Za-z0-9-]+$'),
    "ownerId" bigint NOT NULL,
    "paymentTerm" text NOT NULL CHECK ("paymentTerm" IN (
        'hour', 'week', 'month', 'quarter_year', 'half_year', 'year'
    )),
    "autoProlong" boolean NOT NULL DEFAULT false,
    "createdAt" timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "expiresAt" timestamptz(3) NOT NULL,
    status text NOT NULL CHECK (status IN (
        'active', 'blocked', 'deleted', 'suspended', 'prolong_wait'
    )),
    price bigint NOT NULL CHECK (price >= 0),
    CONSTRAINT services_owner_fk FOREIGN KEY ("ownerId")
        REFERENCES public.accounts(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT services_dates_check CHECK ("expiresAt" >= "createdAt")
);

CREATE INDEX services_owner_id_idx ON public.services ("ownerId");

CREATE TABLE public.transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount bigint NOT NULL CHECK (amount >= 0),
    status text NOT NULL DEFAULT 'not_performed'
        CHECK (status IN ('not_performed', 'performed')),
    "performedAt" timestamptz(3),
    "createdAt" timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    type text NOT NULL CHECK (type IN ('prolong', 'order')),
    "serviceId" bigint NOT NULL,
    CONSTRAINT transactions_service_fk FOREIGN KEY ("serviceId")
        REFERENCES public.services(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT transactions_performed_check CHECK (
        (status = 'not_performed' AND "performedAt" IS NULL)
        OR (status = 'performed' AND "performedAt" IS NOT NULL
            AND "performedAt" >= "createdAt")
    )
);

CREATE INDEX transactions_service_id_idx ON public.transactions ("serviceId");

CREATE TABLE public.model_settings (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    weights jsonb NOT NULL CHECK (jsonb_typeof(weights) = 'object'),
    medium_threshold numeric(5, 2) NOT NULL CHECK (medium_threshold BETWEEN 0 AND 100),
    high_threshold numeric(5, 2) NOT NULL CHECK (high_threshold BETWEEN 0 AND 100),
    horizon_days integer NOT NULL CHECK (horizon_days BETWEEN 1 AND 365),
    updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT model_settings_thresholds_check CHECK (medium_threshold < high_threshold)
);

